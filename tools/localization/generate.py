"""Build checked-in Android resources and the legacy bilingual-call bridge.

Edit catalog.json / translations.tsv / help.json, then run this script.
The English text is the stable lookup key; generated resource names include a hash.
No runtime network, model or translation service is used for interface strings.
"""
import hashlib, json, re
from pathlib import Path
from xml.sax.saxutils import escape

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
LOCALES='es fr de pt ru ja ko ar'.split()
rows=json.loads((HERE/'catalog.json').read_text(encoding='utf-8'))
translations={}
for line in (HERE/'translations.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'):continue
    fields=line.split('|')
    assert len(fields)==9, (fields[0],len(fields))
    i=int(fields[0]);assert i not in translations, i
    translations[i]={l:s.replace('\\n','\n') for l,s in zip(LOCALES,fields[1:])}
translations[171]=json.loads((HERE/'help.json').read_text(encoding='utf-8'))
for i,source in {12:7,25:24,245:219,255:36,266:219,267:211,268:6,270:224}.items():
    translations[i]=translations[source].copy()
translations[221]={l:'Qwen3-1.7B'+translations[178][l] for l in LOCALES}
# Obsolete non-UI matches from the original extraction; never generate them.
rows=[r for r in rows if r['id'] not in {129,130,131,160,176}]
missing=[r['id'] for r in rows if r['id'] not in translations]
assert not missing, ('Missing translations',missing)
for r in rows:
    r.update(translations[r['id']])
    assert all(r[l].strip() for l in LOCALES),r['id']

def key(en):
    stem=re.sub('[^a-z0-9]+','_',en.lower()).strip('_')[:44].rstrip('_')
    return 'ui_'+stem+'_'+hashlib.sha1(en.encode()).hexdigest()[:8]
def xml(s):
    return '"'+escape(s.replace('\\','\\\\').replace('"','\\"').replace("'","\\'").replace('\n','\\n'))+'"'
unique={}
for r in rows:unique.setdefault(r['en'],r)
res=ROOT/'app/src/main/res'
for locale in ['en','zh',*LOCALES]:
    folder=res/('values' if locale=='en' else 'values-'+locale)
    folder.mkdir(parents=True,exist_ok=True)
    if locale not in {'en','zh'}:
        (folder/'strings.xml').write_text('<resources><string name="app_name">Instant Caption</string></resources>\n',encoding='utf-8')
    lines=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by tools/localization/generate.py. -->','<resources>']
    lines+=['    <string name="'+key(en)+'" formatted="false">'+xml(r[locale])+'</string>' for en,r in unique.items()]
    lines+=['</resources>']
    (folder/'ui_strings.xml').write_text('\n'.join(lines)+'\n',encoding='utf-8')

def j(s): return json.dumps(s,ensure_ascii=False)
java=['package com.localcaption.instant;',
      'import android.content.Context;', 'import java.util.*;',
      '/** Generated resource bridge for the existing bilingual UI calls. */',
      'final class UiStrings {',
      '    static final Map<String,Integer> ENGLISH=new LinkedHashMap<>();',
      '    static final Map<String,Integer> STATUS=new LinkedHashMap<>();',
      '    static {']
for en,r in unique.items():java.append('        ENGLISH.put('+j(en)+',R.string.'+key(en)+');')
# Exact state strings and the fixed portions of composed state messages.
states=[r for r in rows if r['id']>=210 or r['id'] in {36,179,180,181,183,195,219}]
states.sort(key=lambda r:-len(r['zh']))
for r in states:java.append('        STATUS.put('+j(r['zh'])+',R.string.'+key(r['en'])+');')
java+=['    }', '''    static String text(Context c,String zh,String en){
        Context localized=AppPrefs.localized(c);
        String language=localized.getResources().getConfiguration().getLocales().get(0).getLanguage();
        if("zh".equals(language))return zh;
        Integer id=ENGLISH.get(en);
        if(id==null){android.util.Log.w("UiStrings","Missing resource: "+en);return en;}
        return localized.getString(id);
    }
    // Caption contents never pass through this method; only application status messages do.
    static String status(Context c,String raw){
        if(raw==null)return "";
        Context localized=AppPrefs.localized(c);
        if("zh".equals(localized.getResources().getConfiguration().getLocales().get(0).getLanguage()))return raw;
        StringBuilder out=new StringBuilder();
        for(int offset=0;offset<raw.length();){
            boolean found=false;
            for(Map.Entry<String,Integer> part:STATUS.entrySet()){
                if(raw.startsWith(part.getKey(),offset)){
                    out.append(localized.getString(part.getValue()));offset+=part.getKey().length();found=true;break;
                }
            }
            if(!found){int cp=raw.codePointAt(offset);out.appendCodePoint(cp);offset+=Character.charCount(cp);}
        }
        return out.toString();
    }
}''']
(ROOT/'app/src/main/java/com/localcaption/instant/UiStrings.java').write_text('\n'.join(java)+'\n',encoding='utf-8')
print(f'Generated {len(unique)} interface resources in 10 languages; {len(states)} status fragments.')
