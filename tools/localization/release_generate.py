"""Generate and validate release-readiness strings for all ten interface languages."""
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT=Path(__file__).resolve().parents[2]
LANGS='en zh es fr de pt ru ja ko ar'.split()
rows={}
for line in Path(__file__).with_name('release.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'):continue
    fields=line.split('|')
    assert len(fields)==11,(fields[0],len(fields))
    key,*values=fields
    assert key not in rows,key
    expected=sorted(re.findall(r'%\d+\$[sd]',values[0]))
    for value in values:assert value.strip() and sorted(re.findall(r'%\d+\$[sd]',value))==expected,key
    rows[key]=values
for i,language in enumerate(LANGS):
    folder=ROOT/'app/src/main/res'/('values' if language=='en' else 'values-'+language)
    lines=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by tools/localization/release_generate.py -->','<resources>']
    for key,values in rows.items():
        value=escape(values[i].replace('"','\\"').replace("'","\\'"))
        formatting='' if re.search(r'%\d+\$[sd]',values[i]) else ' formatted="false"'
        lines.append(f'    <string name="{key}"{formatting}>"{value}"</string>')
    (folder/'release_strings.xml').write_text('\n'.join(lines+['</resources>'])+'\n',encoding='utf-8')
print(f'Validated {len(rows)} strings in {len(LANGS)} languages')
